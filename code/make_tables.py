"""Turn the recorded runs into the tables that go into the midterm report.

Reads results/baselines.jsonl and results/model_profile.jsonl and writes
results/midterm_tables.md. Everything in the report should be generated by this script
rather than copied by hand, so that a re-run cannot silently disagree with the text.

    /home/sarthak/miniconda3/envs/op05/bin/python code/make_tables.py
"""
import json
import os
from collections import defaultdict

RESULTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
ORDER = ["MLP", "LeNet", "ResNet18", "ResNet50", "ResNet101",
         "RNN", "GRU", "LSTM", "BiLSTM", "CNN+GRU", "ViT"]
NICE = {"UT_HAR_data": "UT-HAR", "NTU-Fi_HAR": "NTU-Fi HAR",
        "NTU-Fi-HumanID": "NTU-Fi HumanID", "Widar": "Widar3.0"}


def read(name):
    path = os.path.join(RESULTS, name)
    if not os.path.exists(path):
        return []
    return [json.loads(line) for line in open(path) if line.strip()]


def main():
    runs = [r for r in read("baselines.jsonl") if r.get("tag") == "baseline"]
    prof = {(p["dataset"], p["model"]): p for p in read("model_profile.jsonl")}
    if not runs:
        print("no baseline runs recorded yet")
        return

    acc = {(r["dataset"], r["protocol"], r["model"]): r for r in runs}
    datasets = [d for d in NICE if any(k[0] == d for k in acc)]
    out = ["# Generated result tables", "",
           "Every number here comes from `results/baselines.jsonl` and",
           "`results/model_profile.jsonl`. Regenerate with `code/make_tables.py`.", ""]

    # Table 1: accuracy of every model on every dataset.
    out += ["## Table 1. Test accuracy of the eleven models", "",
            "Final-epoch accuracy, with the best epoch in brackets. Trained with the",
            "benchmark's own recipe (Adam, learning rate 0.001, batch 64).", "",
            "| Model | " + " | ".join(NICE[d] for d in datasets) + " |",
            "|---" * (len(datasets) + 1) + "|"]
    for m in ORDER:
        cells = []
        for d in datasets:
            r = acc.get((d, "original", m))
            cells.append(f"{r['final_acc']:.3f} ({r['best_acc']:.3f})" if r else "-")
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    out.append("")

    # Table 2: is a big model worth it?
    for d in datasets:
        rows = [(m, acc.get((d, "original", m)), prof.get((d, m))) for m in ORDER]
        rows = [(m, a, p) for m, a, p in rows if a]
        if not rows:
            continue
        best = max(a["best_acc"] for _, a, _ in rows)
        out += [f"## Table 2{chr(97 + datasets.index(d))}. Cost against accuracy on "
                f"{NICE[d]}", "",
                "| Model | Accuracy | Gap to best | Parameters | Weights MB | "
                "Latency ms/sample |", "|---|---|---|---|---|---|"]
        for m, a, p in sorted(rows, key=lambda t: -t[1]["best_acc"]):
            mb = a["params"] * 4 / 1e6
            lat = f"{p['ms_per_sample']:.3f}" if p else "-"
            out.append(f"| {m} | {a['best_acc']:.3f} | "
                       f"{best - a['best_acc']:+.3f} | {a['params']:,} | "
                       f"{mb:.1f} | {lat} |")
        out.append("")

    # Table 3: training cost, which is what made the caching work worth doing.
    out += ["## Table 3. Training time actually spent", "",
            "| Dataset | Models trained | Epochs each | Total GPU minutes |",
            "|---|---|---|---|"]
    by_ds = defaultdict(list)
    for r in runs:
        by_ds[r["dataset"]].append(r)
    for d in datasets:
        rs = by_ds[d]
        eps = sorted({r["epochs"] for r in rs})
        out.append(f"| {NICE[d]} | {len(rs)} | {eps[0] if len(eps) == 1 else 'varies'} "
                   f"| {sum(r['train_min'] for r in rs):.1f} |")
    out.append("")

    path = os.path.join(RESULTS, "midterm_tables.md")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("\n".join(out))
    print(f"\nwritten to {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
